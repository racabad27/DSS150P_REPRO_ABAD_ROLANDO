"""Evidence for incremental ingestion: first run, interrupted run, resumed run.

Runs the real CLI commands one after the other and saves their output to
docs/evidence/incremental_ingestion.md:

    1. reset the raw layer and the checkpoint (data/source is never touched)
    2. first incremental run - only 2 quarterly batches "arrive"
    3. a run that is interrupted on purpose after 2 more batches (exit code 75)
    4. the same command again - it resumes from the checkpoint
    5. one more run - nothing is pending, nothing is written
    6. status - final row count and duplicate check

    python scripts/demo_incremental_ingestion.py
    docker compose run --rm pipeline python scripts/demo_incremental_ingestion.py
"""

from __future__ import annotations

import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "docs" / "evidence" / "incremental_ingestion.md"

STEPS = [
    ("Reset raw layer and checkpoint", ["reset-raw", "--yes"], 0),
    ("Run 1 - first incremental run, 2 batches arrive", ["ingest", "--max-batches", "2"], 0),
    ("Run 2 - interrupted on purpose after 2 more committed batches",
     ["ingest", "--fail-after-batches", "2"], 75),
    ("Run 3 - same command again: resumes from the checkpoint", ["ingest"], 0),
    ("Run 4 - rerun with nothing pending (no duplicates appended)", ["ingest"], 0),
    ("Final verification - row counts and duplicate keys", ["status"], 0),
]


def main() -> int:
    lines = [
        "# Evidence: incremental ingestion with interruption and resume",
        "",
        f"Generated by `python scripts/demo_incremental_ingestion.py` on "
        f"{datetime.now(timezone.utc):%Y-%m-%d %H:%M} UTC. Console times are local time.",
        "",
    ]
    failures = 0
    for title, args, expected_code in STEPS:
        command = [sys.executable, "-m", "src.cli", *args]
        completed = subprocess.run(command, cwd=ROOT, capture_output=True, text=True)
        output = (completed.stdout + completed.stderr).strip()
        ok = completed.returncode == expected_code
        failures += not ok
        lines += [
            f"## {title}",
            "",
            f"`python -m src.cli {' '.join(args)}` → exit code **{completed.returncode}** "
            f"(expected {expected_code}) {'✔' if ok else '✘'}",
            "",
            "```text",
            output,
            "```",
            "",
        ]
        print(f"[{'ok' if ok else 'UNEXPECTED'}] {title} (exit {completed.returncode})")
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
